// FRONT-04: Cola de sincronización en segundo plano para mutaciones de gastos cuando no hay red
const bgSyncPlugin = new BackgroundSyncPlugin('gastos-mutations-queue', {
  maxRetentionTime: 24 * 60 // Reintentar hasta por 24 horas (en minutos)
});

registerRoute(
  ({ url }) => url.pathname.startsWith('/api/expenses'),
  new NetworkOnly({
    plugins: [bgSyncPlugin]
  }),
  'POST'
);

